#!/usr/bin/env python3
"""Install and start the GPU monitor in the current package directory."""
import argparse
import fcntl
import hashlib
import os
from pathlib import Path
import shlex
import shutil
import socket
import stat
import subprocess
import sys
import tempfile


def checked(path, required=False):
    path = Path(path)
    if not path.exists() and not path.is_symlink():
        if required:
            raise RuntimeError("Missing package file: {}".format(path))
        return path
    info = path.lstat()
    if stat.S_ISLNK(info.st_mode):
        raise RuntimeError("Symlinks are not supported: {}".format(path))
    if info.st_uid != os.getuid():
        raise RuntimeError("Path must belong to the current user: {}".format(path))
    if not (stat.S_ISREG(info.st_mode) or stat.S_ISDIR(info.st_mode)):
        raise RuntimeError("Not a regular file or directory: {}".format(path))
    return path


def check_package(base):
    if base != base.resolve():
        raise RuntimeError("Use a real package directory without symlink components")
    checked(base, required=True)
    for name in ("monitor.py", "install_server.py", "static/index.html", "static/style.css", "static/app.js"):
        path = checked(base / name, required=True)
        if not path.is_file():
            raise RuntimeError("Expected a regular file: {}".format(path))
    def walk_error(error):
        raise error
    for directory, dirs, files in os.walk(str(base), followlinks=False, onerror=walk_error):
        for name in dirs + files:
            checked(Path(directory) / name, required=True)
    for name in ("gpu-monitor.sh", "gpu_metrics.csv", "monitor.pid", "monitor.log",
                 "monitor.log.1", "monitor.log.2", ".monitor.lock", ".start.lock", ".disabled"):
        path = checked(base / name)
        if path.exists() and not path.is_file():
            raise RuntimeError("Expected a regular file: {}".format(path))
    lock = base / ".monitor.lock"
    if lock.exists():
        with lock.open("r") as handle:
            try:
                fcntl.flock(handle.fileno(), fcntl.LOCK_EX | fcntl.LOCK_NB)
            except BlockingIOError:
                raise RuntimeError("This package is already running. Stop it with ./gpu-monitor.sh stop before reinstalling or changing settings.")


def read_crontab():
    executable = shutil.which("crontab")
    if executable is None:
        raise RuntimeError("--autostart requires an installed crontab command and a running cron service")
    env = dict(os.environ, LC_ALL="C")
    result = subprocess.run([executable, "-l"], stdout=subprocess.PIPE,
                            stderr=subprocess.PIPE, text=True, env=env, timeout=15)
    if result.returncode == 0:
        return executable, result.stdout
    if result.returncode == 1 and "no crontab for" in result.stderr.lower():
        return executable, ""
    raise RuntimeError("Cannot read current user's crontab: {}".format(result.stderr.strip()))


def cron_text(previous, wrapper):
    marker = "# gpu-monitor-portable:" + hashlib.sha256(str(wrapper.parent).encode("utf-8")).hexdigest()[:20]
    # POSIX printf decodes the filename inside double quotes. Cron sees no literal
    # percent sign, shell metacharacter, or whitespace from the user's pathname.
    octal_path = "".join("\\{:03o}".format(byte) for byte in os.fsencode(str(wrapper)))
    command = '/bin/sh "$(printf \'' + octal_path + '\')" ensure >/dev/null 2>&1'
    retained = "".join(line for line in previous.splitlines(keepends=True)
                       if not line.rstrip().endswith(marker))
    if retained and not retained.endswith("\n"):
        retained += "\n"
    return retained + "# GPU monitor directory: {} {}\n@reboot {} {}\n* * * * * {} {}\n".format(
        wrapper.parent, marker, command, marker, command, marker)


def write_wrapper(base, python, nvidia, host, port):
    runtime = base / ".runtime"
    for path in (runtime, runtime / "tmp", runtime / "cache"):
        checked(path)
        path.mkdir(mode=0o700, exist_ok=True)
        checked(path, required=True)
    shell = """#!/bin/sh
# Generated by install_server.py; rerun the installer after moving this directory.
set -eu
umask 077
BASE={base}
PYTHON={python}
export PATH={path}
export TMPDIR="$BASE/.runtime/tmp" TMP="$BASE/.runtime/tmp" TEMP="$BASE/.runtime/tmp"
export XDG_CACHE_HOME="$BASE/.runtime/cache" PYTHONDONTWRITEBYTECODE=1
cd "$BASE"
if [ "$#" -gt 1 ]; then
    echo 'Usage: gpu-monitor.sh [start|ensure|stop|status|serve]' >&2
    exit 2
fi
action=${{1:-status}}
case "$action" in
    start|ensure|stop|status|serve) ;;
    *) echo 'Usage: gpu-monitor.sh [start|ensure|stop|status|serve]' >&2; exit 2 ;;
esac
exec "$PYTHON" "$BASE/monitor.py" "$action" --host {host} --port {port}
""".format(base=shlex.quote(str(base)), python=shlex.quote(python),
           path=shlex.quote(str(Path(nvidia).parent) + ":/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin"),
           host=shlex.quote(host), port=port)
    wrapper = checked(base / "gpu-monitor.sh")
    fd, temporary = tempfile.mkstemp(prefix=".install-", suffix=".tmp", dir=str(runtime / "tmp"))
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as handle:
            handle.write(shell)
            handle.flush()
            os.fsync(handle.fileno())
        os.chmod(temporary, 0o700)
        checked(wrapper)
        os.replace(temporary, str(wrapper))
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)
    os.environ.update(TMPDIR=str(runtime / "tmp"), TMP=str(runtime / "tmp"),
                      TEMP=str(runtime / "tmp"), XDG_CACHE_HOME=str(runtime / "cache"),
                      PYTHONDONTWRITEBYTECODE="1")
    return wrapper


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--host", default="127.0.0.1", help="IPv4 address to listen on (default: 127.0.0.1)")
    parser.add_argument("--port", type=int, default=18770, help="HTTP port (default: 18770)")
    parser.add_argument("--autostart", action="store_true", help="add cron jobs to start at boot and recover after an interruption")
    args = parser.parse_args()
    if sys.version_info < (3, 7):
        parser.error("Python 3.7 or newer is required")
    if not sys.platform.startswith("linux"):
        parser.error("Run this installer on the Linux server that hosts the NVIDIA GPUs")
    if os.getuid() == 0:
        parser.error("Run this installer as a regular user without sudo")
    if not 1024 <= args.port <= 65535:
        parser.error("--port must be between 1024 and 65535")
    if any(character in args.host for character in "\r\n\x00"):
        parser.error("Invalid --host")
    os.umask(0o077)
    script = Path(os.path.abspath(__file__))
    if script.is_symlink():
        raise RuntimeError("Run install_server.py directly, not through a symlink")
    base = script.parent
    check_package(base)
    python = os.path.realpath(sys.executable)
    if any(character in str(base) + python for character in "\r\n"):
        raise RuntimeError("Newlines are not supported in installation or Python paths")
    nvidia = shutil.which("nvidia-smi")
    if nvidia is None:
        raise RuntimeError("nvidia-smi was not found in PATH; install/fix the server's NVIDIA driver first")
    probe = subprocess.run([nvidia, "--list-gpus"], stdout=subprocess.PIPE,
                           stderr=subprocess.PIPE, text=True, timeout=30)
    if probe.returncode or not probe.stdout.strip():
        raise RuntimeError("nvidia-smi cannot list GPUs: {}".format((probe.stderr or probe.stdout).strip()))
    # Binding is only a preflight check. Never stop an existing listener.
    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as listener:
        listener.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
        try:
            listener.bind((args.host, args.port))
        except OSError as error:
            raise RuntimeError("Cannot bind {}:{} (no existing service was changed): {}".format(args.host, args.port, error))
    cron = read_crontab() if args.autostart else None
    wrapper = write_wrapper(base, python, nvidia, args.host, args.port)
    result = subprocess.run([str(wrapper), "start"], timeout=45)
    if result.returncode:
        raise RuntimeError("Monitor start failed; inspect {}/monitor.log. No cron entries were installed.".format(base))
    if cron:
        executable, previous = cron
        # Re-read immediately before writing to detect unrelated concurrent edits.
        current_executable, current = read_crontab()
        if current != previous or current_executable != executable:
            raise RuntimeError("Monitor is running, but crontab changed during installation; autostart was not installed")
        result = subprocess.run([executable, "-"], input=cron_text(previous, wrapper),
                                stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                                text=True, env=dict(os.environ, LC_ALL="C"), timeout=15)
        if result.returncode:
            raise RuntimeError("Monitor is running, but cron installation failed: {}".format(result.stderr.strip()))
        print("Autostart/recovery entries installed for this user. The server's cron service must be running.")
    print("Installed in: {}".format(base))
    print("Listen address: http://{}:{}".format(args.host, args.port))
    print("Manage: {} [start|stop|status]".format(shlex.quote(str(wrapper))))
    if not args.autostart:
        print("Autostart is disabled. To add it later: stop this monitor, then rerun this installer with --autostart.")
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except (OSError, RuntimeError, subprocess.SubprocessError) as error:
        print("Installation failed: {}".format(error), file=sys.stderr)
        sys.exit(1)
